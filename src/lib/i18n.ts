const DICT: Record<Lang, Record<Key, string>> = { en, es };

export type Vars = Record<string, string | number>;

const fill = (s: string, vars?: Vars) => s.replace(/\{(\w+)\}/g, (m, k) => (vars && k in vars ? String(vars[k]) : m));

export function translator(lang: Lang) {
  const d = DICT[lang];
  const t = (key: Key, vars?: Vars) => fill(d[key], vars);
  /** Picks the ".one" or ".other" form; {n} is filled with the count. */
  const n = (base: PluralBase, count: number, vars?: Vars) =>
    fill(d[`${base}.${count === 1 ? "one" : "other"}` as Key], { n: count, ...vars });
  return Object.assign(t, { n, lang });
}

export type T = ReturnType<typeof translator>;

export const isKey = (k: string): k is Key => k in en;

/** An error whose message is a translation key, so the UI can show it in the viewer's language. */
export class AppError extends Error {
  constructor(
    public key: Key,
    public vars?: Vars,
  ) {
    super(key);
  }
}
